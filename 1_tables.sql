-- Tạo các bảng
-- Các bảng độc lập (không có khóa ngoại)
CREATE TABLE KHUVUC (
    MaKV VARCHAR(50) PRIMARY KEY,
    TenKhuVuc NVARCHAR(100),
    DiaChi NVARCHAR(255)
);

CREATE TABLE LOAIPHONG (
    MaLoai VARCHAR(50) PRIMARY KEY,
    TenLoai NVARCHAR(100)
);

CREATE TABLE THIETBI (
    MaThietBi VARCHAR(50) PRIMARY KEY,
    TenThietBi NVARCHAR(100),
    GiaTienBoiThuong DECIMAL(18, 2)
);

CREATE TABLE NHANVIEN (
    MaNV VARCHAR(50) PRIMARY KEY,
    TenNV NVARCHAR(100)
);

CREATE TABLE NHOMTHUE (
    MaNhom VARCHAR(50) PRIMARY KEY,
    MaKHDaiDien VARCHAR(50) NULL -- Gắn foreign key sau
);

-- 3 loại nhân viên
CREATE TABLE NV_KDOANH (
    MaNV VARCHAR(50) PRIMARY KEY,
    FOREIGN KEY (MaNV) REFERENCES NHANVIEN(MaNV)
);

CREATE TABLE NV_QLY (
    MaNV VARCHAR(50) PRIMARY KEY,
    FOREIGN KEY (MaNV) REFERENCES NHANVIEN(MaNV)
);

CREATE TABLE NV_KTOAN (
    MaNV VARCHAR(50) PRIMARY KEY,
    FOREIGN KEY (MaNV) REFERENCES NHANVIEN(MaNV)
);

-- Các bảng có khóa ngoại
CREATE TABLE KHACHHANG (
    MaKH VARCHAR(50) PRIMARY KEY,
    HoTen NVARCHAR(100),
    SDT VARCHAR(20),
    Email VARCHAR(100),
    GioiTinh NVARCHAR(10),
    CCCD VARCHAR(20)
);

